import 'session_recorder.dart';

/// How the exported test starts the app and what it is called.
final class ExportOptions {
  const ExportOptions({
    required this.description,
    required this.imports,
    required this.appMain,
    this.runCommand,
  });

  /// Name of the generated `testWidgets`.
  final String description;

  /// Import URIs, optionally with a prefix: `package:my_app/main.dart as app`.
  final List<String> imports;

  /// Dart statements that start the app, e.g. `app.main();`.
  final String appMain;

  /// Shown in the header comment, e.g. `flutter test integration_test/x_test.dart`.
  final String? runCommand;
}

final _testName = RegExp(r'^[a-z][a-z0-9_]*$');

/// File name for the test [name] (snake_case), e.g. `login` → `login_test.dart`.
///
/// Throws [ArgumentError] when [name] is not a valid snake_case Dart file name.
String testFileName(String name) {
  if (!_testName.hasMatch(name)) {
    throw ArgumentError(
      'Invalid test name "$name": use snake_case letters, digits and _, '
      'starting with a letter (e.g. "login_flow").',
    );
  }
  return name.endsWith('_test') ? '$name.dart' : '${name}_test.dart';
}

/// Dart source of an integration test that replays [steps] with the plain
/// `flutter_test` API (no MCP involved).
String generateIntegrationTest(
  List<RecordedStep> steps,
  ExportOptions options,
) => _Generator(options).generate(steps);

final class _Generator {
  _Generator(this.options);

  final ExportOptions options;
  final _body = StringBuffer();
  final _envNames = <String>{};
  var _material = false;
  var _services = false;
  var _gestures = false;
  var _waitFor = false;
  var _textOf = false;

  String generate(List<RecordedStep> steps) {
    for (final step in steps) {
      _body.writeln();
      _step(step);
    }
    return _file();
  }

  String _file() {
    final out = StringBuffer()
      ..writeln(
        '// Generated by mcp_integration_test_server (export_test) from a '
        'recorded',
      )
      ..writeln(
        '// MCP session. It only uses flutter_test / integration_test: '
        'edit freely.',
      );
    if (options.runCommand case final run?) {
      out
        ..writeln('//')
        ..writeln('// Run: $run');
    }
    if (_envNames.isNotEmpty) {
      out
        ..writeln('//')
        ..writeln(
          '// Values typed with enterEnv are read with String.fromEnvironment:',
        )
        ..writeln(
          '// pass ${_envNames.join(', ')} with --dart-define-from-file=<env file>.',
        );
    }
    out.writeln();
    if (_gestures) out.writeln("import 'package:flutter/gestures.dart';");
    if (_material) out.writeln("import 'package:flutter/material.dart';");
    if (_services) out.writeln("import 'package:flutter/services.dart';");
    out
      ..writeln("import 'package:flutter_test/flutter_test.dart';")
      ..writeln("import 'package:integration_test/integration_test.dart';");
    if (options.imports.isNotEmpty) {
      out.writeln();
      for (final import in options.imports) {
        out.writeln(_importDirective(import));
      }
    }
    out
      ..writeln()
      ..writeln('Future<void> _startApp() async {');
    for (final line in options.appMain.trim().split('\n')) {
      out.writeln(line.trim().isEmpty ? '' : '  ${line.trimRight()}');
    }
    out
      ..writeln('}')
      ..writeln()
      ..writeln('void main() {')
      ..writeln(
        '  final binding = IntegrationTestWidgetsFlutterBinding.ensureInitialized();',
      )
      ..writeln(
        '  binding.framePolicy = LiveTestWidgetsFlutterBindingFramePolicy.fullyLive;',
      )
      ..writeln()
      ..writeln(
        '  testWidgets(${_literal(options.description)}, (tester) async {',
      )
      ..writeln('    await _startApp();')
      ..writeln('    await _settle(tester);')
      ..write(_body)
      ..writeln('  });')
      ..writeln('}')
      ..write(_settleHelper);
    if (_waitFor) out.write(_waitForHelper);
    if (_textOf) out.write(_textOfHelper);
    return out.toString();
  }

  // --- steps -------------------------------------------------------------

  void _step(RecordedStep step) {
    final a = step.args;
    switch (step.tool) {
      case 'tap':
        _line('await tester.tap(${_target(a['finder'])});');
        _afterAction(a);
      case 'longPress':
        _line('await tester.longPress(${_target(a['finder'])});');
        _afterAction(a);
      case 'doubleTap':
        final target = _target(a['finder']);
        _gestures = true;
        _line('await tester.tap($target);');
        _line('await tester.pump(kDoubleTapMinTime);');
        _line('await tester.tap($target);');
        _afterAction(a);
      case 'tapAt':
        _material = true;
        _line(
          'await tester.tapAt(const Offset(${_num(a['x'])}, ${_num(a['y'])}));',
        );
        _afterAction(a);
      case 'enterText':
        _enterText(a, _literal(a['text'] as String? ?? ''));
      case 'enterEnv':
        final name = a['name'] as String;
        _envNames.add(name);
        _enterText(a, 'const String.fromEnvironment(${_literal(name)})');
      case 'drag':
        _material = true;
        _line(
          'await tester.drag(${_target(a['finder'])}, '
          'const Offset(${_num(a['dx'])}, ${_num(a['dy'])}));',
        );
        _afterAction(a);
      case 'fling':
        _material = true;
        _line(
          'await tester.fling(${_target(a['finder'])}, '
          'const Offset(${_num(a['dx'])}, ${_num(a['dy'])}), '
          '${_num(a['speed'] ?? 1000)});',
        );
        _afterAction(a);
      case 'scrollUntilVisible':
        _scrollUntilVisible(a);
      case 'pressBack':
        _line('await tester.binding.handlePopRoute();');
        _line('await _settle(tester);');
      case 'sendKey':
        _services = true;
        _line('await tester.sendKeyEvent(LogicalKeyboardKey.${a['key']});');
        _afterAction(a);
      case 'pump':
        _line('await tester.pump(${_duration(a['ms'] ?? 0)});');
      case 'pumpAndSettle':
        _line(
          'await tester.pumpAndSettle(const Duration(milliseconds: 100), '
          'EnginePhase.sendSemanticsUpdate, ${_duration(a['timeoutMs'] ?? 10000)});',
        );
      case 'waitFor':
        _waitFor = true;
        final absent = a['absent'] == true ? ', absent: true' : '';
        final timeout = a['timeoutMs'] == null
            ? ''
            : ', timeout: ${_duration(a['timeoutMs'])}';
        _line(
          'await _waitFor(tester, ${_finder(a['finder'])}$absent$timeout);',
        );
      case 'expect':
        _expect(step);
      case 'app_restart':
        _material = true;
        _line('await tester.pumpWidget(const SizedBox.shrink());');
        _line('await _startApp();');
        _line('await _settle(tester, timeout: const Duration(seconds: 5));');
      default:
        _line('// Not replayable: ${step.tool}');
    }
  }

  void _enterText(Map<String, Object?> a, String text) {
    _line('await tester.enterText(${_target(a['finder'])}, $text);');
    if (a['submit'] == true) {
      _services = true;
      _line('await tester.testTextInput.receiveAction(TextInputAction.done);');
    }
    _afterAction(a);
  }

  void _scrollUntilVisible(Map<String, Object?> a) {
    _material = true;
    final scrollable = a['scrollable'] == null
        ? 'find.byType(Scrollable).first'
        : _target(a['scrollable']);
    final dx = a['dx'] ?? 0;
    final dy = a['dy'] ?? a['delta'] ?? -200;
    final maxScrolls = a['maxScrolls'] == null
        ? ''
        : ', maxIteration: ${a['maxScrolls']}';
    _line(
      'await tester.dragUntilVisible(${_target(a['finder'])}, $scrollable, '
      'const Offset(${_num(dx)}, ${_num(dy)})$maxScrolls);',
    );
    _afterAction(a);
  }

  void _expect(RecordedStep step) {
    final a = step.args;
    if (step.failure case final failure?) {
      _line('// Did not hold while recording, so it is not replayed:');
      _line('// expect: ${failure.replaceAll('\n', ' ')}');
      return;
    }
    final finder = _finder(a['finder']);
    final count = (a['count'] as num?)?.toInt();
    final exists = a['exists'] as bool?;
    final text = a['text'] as String?;
    if (count != null) {
      _line(
        'expect($finder, ${count == 0 ? 'findsNothing' : 'findsNWidgets($count)'});',
      );
    }
    if (exists != null) {
      _line('expect($finder, ${exists ? 'findsWidgets' : 'findsNothing'});');
    }
    if (text != null) {
      _line(
        'expect(find.descendant(of: ${_target(a['finder'])}, '
        'matching: find.text(${_literal(text)}), matchRoot: true), findsWidgets);',
      );
    }
    if (count == null && exists == null && text == null) {
      _line('expect($finder, findsWidgets);');
    }
  }

  void _afterAction(Map<String, Object?> a) {
    if (a['settle'] == false) {
      _line('await tester.pump();');
      return;
    }
    final timeout = a['settleTimeoutMs'];
    _line(
      timeout == null
          ? 'await _settle(tester);'
          : 'await _settle(tester, timeout: ${_duration(timeout)});',
    );
  }

  void _line(String code) => _body.writeln('    $code');

  // --- finders -----------------------------------------------------------

  /// The single widget an action works on, like `FinderSpec.target`.
  String _target(Object? spec) {
    final index = _index(spec);
    final finder = _finder(spec);
    return index == 0 ? '$finder.first' : '$finder.at($index)';
  }

  static int _index(Object? spec) =>
      spec is Map ? (spec['index'] as num?)?.toInt() ?? 0 : 0;

  /// Every widget matching [spec], mirroring `FinderSpec.finder`.
  String _finder(Object? spec) {
    if (spec is! Map) {
      throw ArgumentError('Recorded step has no finder');
    }
    final offstage = spec['includeOffstage'] == true;
    final skip = offstage ? ', skipOffstage: false' : '';
    final criteria = [
      for (final field in const [
        'key',
        'text',
        'textContaining',
        'tooltip',
        'type',
        'semanticsLabel',
      ])
        if (spec[field] != null) (field, '${spec[field]}'),
    ];
    if (criteria.isEmpty) {
      throw ArgumentError('Recorded finder has no criteria: $spec');
    }

    String base;
    if (criteria.length == 1) {
      final (field, value) = criteria.single;
      final lit = _literal(value);
      switch (field) {
        case 'key':
          _material = true;
          base = 'find.byKey(const ValueKey<String>($lit)$skip)';
        case 'text':
          base = 'find.text($lit$skip)';
        case 'textContaining':
          base = 'find.textContaining($lit$skip)';
        case 'tooltip':
          base = 'find.byTooltip($lit$skip)';
        default:
          base = _predicate(criteria, skip);
      }
    } else {
      base = _predicate(criteria, skip);
    }

    final within = spec['within'];
    if (within == null) return base;
    return 'find.descendant(of: ${_target(within)}, matching: $base$skip)';
  }

  String _predicate(List<(String, String)> criteria, String skip) {
    final checks = <String>[];
    final description = <String>[];
    for (final (field, value) in criteria) {
      final lit = _literal(value);
      description.add('$field $value');
      switch (field) {
        case 'key':
          _material = true;
          checks.add('w.key == const ValueKey<String>($lit)');
        case 'text':
          _material = _textOf = true;
          checks.add('_textOf(w) == $lit');
        case 'textContaining':
          _material = _textOf = true;
          checks.add('(_textOf(w)?.contains($lit) ?? false)');
        case 'tooltip':
          _material = true;
          checks.add('(w is Tooltip && w.message == $lit)');
        case 'type':
          checks.add('w.runtimeType.toString() == $lit');
        case 'semanticsLabel':
          _material = true;
          checks.add('(w is Semantics && w.properties.label == $lit)');
      }
    }
    return 'find.byWidgetPredicate((w) => ${checks.join(' && ')}, '
        'description: ${_literal(description.join(', '))}$skip)';
  }

  // --- literals ----------------------------------------------------------

  static String _importDirective(String import) {
    final parts = import.trim().split(RegExp(r'\s+as\s+'));
    final uri = parts.first.replaceAll(RegExp(r'''^['"]|['"]$'''), '');
    return parts.length > 1
        ? 'import ${_literal(uri)} as ${parts[1]};'
        : 'import ${_literal(uri)};';
  }

  static String _duration(Object? ms) =>
      'const Duration(milliseconds: ${(ms as num).toInt()})';

  static String _num(Object? value) {
    if (value is! num) {
      throw ArgumentError('Expected a number, got $value');
    }
    return value is int || value == value.roundToDouble()
        ? '${value.toInt()}'
        : '$value';
  }
}

/// A single-quoted Dart string literal for [value].
String _literal(String value) {
  final out = StringBuffer("'");
  for (final rune in value.runes) {
    out.write(switch (rune) {
      0x5C => r'\\',
      0x27 => r"\'",
      0x24 => r'\$',
      0x0A => r'\n',
      0x0D => r'\r',
      0x09 => r'\t',
      < 0x20 => '\\u{${rune.toRadixString(16)}}',
      _ => String.fromCharCode(rune),
    });
  }
  out.write("'");
  return out.toString();
}

const _settleHelper = r'''

/// Pumps until no frame is scheduled and no animation is running (two idle
/// checks in a row), or [timeout] elapses. Unlike pumpAndSettle it does not
/// throw on endless animations, matching the MCP session.
Future<void> _settle(
  WidgetTester tester, {
  Duration timeout = const Duration(seconds: 3),
}) async {
  final clock = Stopwatch()..start();
  var idle = 0;
  while (idle < 2 && clock.elapsed < timeout) {
    await tester.pump(const Duration(milliseconds: 50));
    final busy =
        tester.binding.hasScheduledFrame ||
        tester.binding.transientCallbackCount > 0;
    idle = busy ? 0 : idle + 1;
  }
}
''';

const _waitForHelper = r'''

/// Pumps until [finder] matches (or stops matching with [absent]).
Future<void> _waitFor(
  WidgetTester tester,
  Finder finder, {
  bool absent = false,
  Duration timeout = const Duration(seconds: 10),
}) async {
  final clock = Stopwatch()..start();
  while (finder.evaluate().isNotEmpty == absent) {
    if (clock.elapsed > timeout) {
      fail(
        'Timed out after ${timeout.inMilliseconds}ms waiting for $finder '
        'to be ${absent ? 'absent' : 'present'}',
      );
    }
    await tester.pump(const Duration(milliseconds: 100));
  }
}
''';

const _textOfHelper = r'''

/// Text of a Text or EditableText, as the MCP finder matches it.
String? _textOf(Widget w) => switch (w) {
  Text(:final data, :final textSpan) => data ?? textSpan?.toPlainText(),
  EditableText(:final controller) => controller.text,
  _ => null,
};
''';
